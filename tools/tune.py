#!/usr/bin/env python3
"""Compiled defaults of tuned kernels, measured on each target's machine (backend/tune, issue #54).

  tune.py KERNEL [--target T ...]
      On the Mac: copy this working tree to each target's tuning machine (vm.py) and run
      `tune.py --measure` there; write the results to backend/KERNEL/tuned.json (with the machine,
      CPU, date and commit) and render backend/KERNEL/tuned.hpp from it. Targets not named keep
      their record. Each run's full output goes to
      ~/Documents/hpc_library-explore/tune/KERNEL/<target>.txt.
  tune.py --measure KERNEL --target T
      On a VM: build backend/KERNEL/tune.cpp for target T (the pinned GCC image, -O2 and the
      target's flags) and run it on the last core under /tmp/bench.lock. It prints lines
      "field <name> <type> <value>..." (the defaults) and "# ..." (diagnostics).
  tune.py --check
      Every backend/*/tuned.hpp is the rendering of its tuned.json, with every target in TARGETS
      and the same fields for each, and tune::Target (backend/tune/tune.hpp) lists TARGETS in order.
      kernel.py check runs it.

A target's tuning machine is its timing machine; untimed x86 targets (scalar, sse) use lc-bench.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kernel import TARGETS, bench_lock, build, require_cpu, sh  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RAW = Path.home() / 'Documents' / 'hpc_library-explore' / 'tune'
UNTIMED_MACHINE = 'lc-bench'


def machine(target: str) -> str:
    return TARGETS[target]['time'] or UNTIMED_MACHINE


def git(*args: str) -> str:
    return subprocess.run(['git', *args], check=True, capture_output=True, text=True, cwd=ROOT).stdout.strip()


def parse_fields(output: str) -> list[list]:
    """[name, type, [values as printed]] per "field" line, in order."""
    fields = []
    for line in output.splitlines():
        if line.startswith('field '):
            _, name, kind, *values = line.split()
            fields.append([name, kind, values])
    return fields


def wrap(values: list[str], indent: str, width: int = 100) -> list[str]:
    lines, line = [], ''
    for v in values:
        piece = f'{v},'
        if line and len(indent) + len(line) + 1 + len(piece) > width:
            lines.append(indent + line)
            line = piece
        else:
            line = f'{line} {piece}' if line else piece
    lines.append(indent + line)
    return lines


def render(kernel: str, record: dict) -> str:
    """tuned.hpp from tuned.json: one array per field, one entry per target in TARGETS order."""
    targets = record['targets']
    out = [f'// Generated by tools/tune.py {kernel} from tuned.json; do not edit. Compiled defaults per',
           '// target, in tune::Target order, measured with the target\'s flags on:']
    for t in TARGETS:
        r = targets[t]
        out.append(f'//   {t}: {r["machine"]} ({r["cpu"]}), {r["date"]}, commit {r["commit"]}')
    out += ['#pragma once', '', f'namespace fps::{kernel}::tuned {{', '']
    for i, (name, kind, values) in enumerate(targets[next(iter(TARGETS))]['fields']):
        rows = [targets[t]['fields'][i][2] for t in TARGETS]
        if len(values) == 1:
            out.append(f'inline constexpr {kind} {name}[] = {{{", ".join(row[0] for row in rows)}}};')
        else:
            out.append(f'inline constexpr {kind} {name}[][{len(values)}] = {{')
            for t, row in zip(TARGETS, rows):
                out.append(f'    {{  // {t}')
                out += wrap(row, ' ' * 8)
                out.append('    },')
            out.append('};')
        out.append('')
    out.append(f'}}  // namespace fps::{kernel}::tuned')
    return '\n'.join(out) + '\n'


def problems(kernel_dir: Path) -> list[str]:
    record_path, header_path = kernel_dir / 'tuned.json', kernel_dir / 'tuned.hpp'
    if not header_path.exists():
        return [f'{header_path} missing']
    record = json.loads(record_path.read_text())
    missing = [t for t in TARGETS if t not in record['targets']]
    if missing:
        return [f'{record_path}: no table for {", ".join(missing)}']
    shapes = {t: [(name, kind, len(values)) for name, kind, values in r['fields']]
              for t, r in record['targets'].items()}
    differ = [t for t in TARGETS if shapes[t] != shapes[next(iter(TARGETS))]]
    if differ:
        return [f'{record_path}: fields of {", ".join(differ)} differ from {next(iter(TARGETS))}']
    if render(kernel_dir.name, record) != header_path.read_text():
        return [f'{header_path} is not the rendering of {record_path.name}: run tools/tune.py {kernel_dir.name}']
    return []


def check() -> int:
    errors = []
    enum = re.search(r'enum class Target \{([^}]*)\}', (ROOT / 'backend/tune/tune.hpp').read_text())
    names = [n.strip() for n in enum.group(1).split(',')] if enum else []
    if names != list(TARGETS):
        errors.append(f'tune::Target lists {names}, TARGETS in tools/kernel.py {list(TARGETS)}')
    for record in sorted(ROOT.glob('backend/*/tuned.json')):
        errors += problems(record.parent)
    for error in errors:
        print(f'FAIL {error}')
    return int(bool(errors))


def measure(kernel: str, target: str) -> int:
    """On the tuning machine: build and run backend/<kernel>/tune.cpp, print its output."""
    require_cpu(target)
    tree = Path('.')
    pin = f'taskset -c {os.cpu_count() - 1} '
    with bench_lock():  # the build too: this is a timing machine
        binary = build(tree, kernel, 'tune.cpp', target)
        # Run a copy: the linker leaves the code on scattered 4 KiB page-cache frames, and on Zen 5
        # that made variants 1.1-2.3x slow in one binary file and not in a copy of it; cp writes
        # 64 KiB folios (backend/factorials/notes.md, issue #70).
        copy = binary.with_name(binary.name + '-copy')
        copy.unlink(missing_ok=True)
        subprocess.run(['cp', str(binary), str(copy)], check=True)
        result = sh({'w': tree}, lambda _: pin + './' + str(copy.relative_to(tree)))
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    return result.returncode


def remote(kernel: str, targets: list[str], commit: str) -> dict:
    """Run --measure for the targets on their machines; one thread per machine. Returns target ->
    record. Exits on any failure."""
    from vm import ship, ssh, working_tree_tar
    tar = working_tree_tar()
    by_machine: dict[str, list[str]] = {}
    for t in targets:
        by_machine.setdefault(machine(t), []).append(t)

    def run(vm: str) -> dict:
        path = ship(vm, f'tune-{kernel}', tar)
        records = {}
        for t in by_machine[vm]:
            print(f'[{t}] measuring on {vm}', file=sys.stderr, flush=True)
            result = ssh(vm, f'cd {path} && python3 tools/tune.py --measure {kernel} --target {t}', capture=True)
            output = result.stdout.decode()
            raw = RAW / kernel / f'{t}.txt'
            raw.parent.mkdir(parents=True, exist_ok=True)
            raw.write_text(output + result.stderr.decode())
            if result.returncode:
                sys.exit(f'[{t}] tune.cpp failed on {vm}; output in {raw}')
            cpu = next((line.split(' ', 2)[2] for line in output.splitlines() if line.startswith('# cpu ')), vm)
            records[t] = {'machine': vm, 'cpu': cpu, 'flags': TARGETS[t]['flags'],
                          'date': datetime.date.today().isoformat(), 'commit': commit,
                          'fields': parse_fields(output)}
        return records

    with ThreadPoolExecutor(len(by_machine)) as pool:
        results = list(pool.map(run, by_machine))
    return {t: r for records in results for t, r in records.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('kernel', nargs='?')
    parser.add_argument('--target', action='append', choices=TARGETS)
    parser.add_argument('--measure', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        return check()
    if not args.kernel or not (ROOT / 'backend' / args.kernel / 'tune.cpp').exists():
        sys.exit('name a kernel with a backend/<kernel>/tune.cpp')
    if args.measure:
        if not args.target or len(args.target) != 1:
            sys.exit('--measure takes one --target')
        return measure(args.kernel, args.target[0])
    commit = git('rev-parse', '--short', 'HEAD') + ('+changes' if git('status', '--porcelain') else '')
    kernel_dir = ROOT / 'backend' / args.kernel
    path = kernel_dir / 'tuned.json'
    record = json.loads(path.read_text()) if path.exists() else {'kernel': args.kernel, 'targets': {}}
    record['targets'].update(remote(args.kernel, args.target or list(TARGETS), commit))
    record['targets'] = {t: record['targets'][t] for t in TARGETS if t in record['targets']}
    path.write_text(json.dumps(record, indent=1) + '\n')
    if all(t in record['targets'] for t in TARGETS):
        (kernel_dir / 'tuned.hpp').write_text(render(args.kernel, record))
    errors = problems(kernel_dir)
    for error in errors:
        print(f'FAIL {error}')
    return int(bool(errors))


if __name__ == '__main__':
    sys.exit(main())
